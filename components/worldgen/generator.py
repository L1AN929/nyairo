def infer_matter_profile(
    kind: str,
    *,
    name: str = "",
    portable: bool = False,
    capacity: int = 0,
    note: str = "",
    affordance_traits: Optional[Sequence[str]] = None,
) -> dict[str, Any]:
    """按品类/名称/备注推断一件物件的物质档（确定性，纯函数）。

    返回的字典只含存在的字段；``ambient_zone`` / ``water_source`` /
    ``capacity_slots`` / ``item_kind`` / ``paper_like`` 总是给出，食品饮料
    另带 ``shelf_life_hours`` 与 ``portions``；柜架类容器带
    ``assembly_role="host_frame"``，成叠纸品带 ``material_units``。
    调用方应再经 :func:`schema.normalize_matter_profile` 校验后落盘。
    """
    haystack = f"{kind or ''} {name or ''} {note or ''}".strip().lower()
    capacity_value = int(capacity or 0)

    def _hit(keywords: Sequence[str]) -> bool:
        return any(keyword in haystack for keyword in keywords)

    if _hit(_MATTER_COLD_KEYWORDS):
        return {
            "ambient_zone": "cold",
            "water_source": False,
            "capacity_slots": max(capacity_value or 8, 6),
            "item_kind": "everyday",
            "paper_like": False,
        }
    if _hit(_MATTER_HEATING_KEYWORDS):
        return {
            "ambient_zone": "heating",
            "water_source": False,
            "capacity_slots": max(capacity_value or 3, 2),
            "item_kind": "everyday",
            "paper_like": False,
        }
    if _hit(_MATTER_WATER_KEYWORDS):
        return {
            "ambient_zone": "room",
            "water_source": True,
            "capacity_slots": max(capacity_value or 4, 2),
            "item_kind": "everyday",
            "paper_like": False,
        }
    if _hit(_MATTER_PAPER_KEYWORDS):
        profile = {
            "ambient_zone": "room",
            "water_source": False,
            "capacity_slots": 0,
            "item_kind": "paper",
            "paper_like": True,
        }
        # 一叠纸/一沓卡片天然可按张拆用；单本日记、信件不标份数。
        if _hit(_MATTER_STACK_KEYWORDS):
            profile["material_units"] = 4
        return profile
    if _hit(_MATTER_VESSEL_KEYWORDS):
        return {
            "ambient_zone": "room",
            "water_source": False,
            "capacity_slots": max(capacity_value or 2, 1),
            "item_kind": "vessel",
            "paper_like": False,
            "portions": 1,
        }
    if _hit(_MATTER_DRINK_KEYWORDS):
        return {
            "ambient_zone": "room",
            "water_source": False,
            "capacity_slots": 0,
            "item_kind": "drink",
            "paper_like": False,
            "shelf_life_hours": 48,
            "portions": 2,
        }
    if _hit(_MATTER_PREPARED_KEYWORDS):
        return {
            "ambient_zone": "room",
            "water_source": False,
            "capacity_slots": 0,
            "item_kind": "prepared_food",
            "paper_like": False,
            "shelf_life_hours": 24,
            "portions": 1,
        }
    if _hit(_MATTER_INGREDIENT_KEYWORDS):
        return {
            "ambient_zone": "room",
            "water_source": False,
            "capacity_slots": 0,
            "item_kind": "ingredient",
            "paper_like": False,
            "shelf_life_hours": 48,
            "portions": 2,
        }
    if _hit(_MATTER_CONTAINER_KEYWORDS):
        # 有盛放格位的柜/架/桌天然是"可装入隔板/配件的容器"。
        return {
            "ambient_zone": "room",
            "water_source": False,
            "capacity_slots": max(capacity_value or 6, 3),
            "item_kind": "everyday",
            "paper_like": False,
            "assembly_role": "host_frame",
        }
    return {
        "ambient_zone": "room",
        "water_source": False,
        "capacity_slots": max(capacity_value, 0),
        "item_kind": "everyday",
        "paper_like": False,
    }


#: The only optional affordance keys a template may carry, beside the legacy pair.
AFFORDANCE_TEMPLATE_OPTIONAL_KEYS = ("title", "suggested_seconds", "execution")


def _template_affordances(entries: Any, *, where: str) -> list[dict[str, Any]]:
    """Build rules affordances from the template's list form.

    Legacy entries stay ``[affordance_id, description]``; an entry may instead carry a third
    mapping with the optional ``title`` / ``suggested_seconds`` keys.  No other shape is
    invented here: values themselves are checked by ``schema.validate_rules_doc`` when the
    generated documents are validated.
    """
    built: list[dict[str, Any]] = []
    for index, item in enumerate(entries or []):
        at = f"{where}[{index}]"
        if not isinstance(item, (list, tuple)) or len(item) not in (2, 3):
            raise schema.WorldPackageError(
                f"{at} 必须是 [affordance_id, description] 或 "
                "[affordance_id, description, {title/suggested_seconds/execution}]"
            )
        affordance = {"affordance_id": item[0], "description": item[1]}
        if len(item) == 3:
            meta = item[2]
            if not isinstance(meta, dict) or not set(meta) <= set(AFFORDANCE_TEMPLATE_OPTIONAL_KEYS):
                raise schema.WorldPackageError(
                    f"{at} 的第三个元素只允许包含 title/suggested_seconds 的对象"
                )
            for key in AFFORDANCE_TEMPLATE_OPTIONAL_KEYS:
                if key in meta:
                    affordance[key] = meta[key]
        built.append(affordance)
    return built


def _slugify_streets(rng: random.Random, template: dict[str, Any], count: int) -> list[dict[str, Any]]:
    names = list(template["street_names"])
    rng.shuffle(names)
    streets = []
    for index in range(count):
        streets.append(
            {
                "location_id": f"street_{index + 1}",
                "name": names[index % len(names)] if index < len(names) else f"{names[0]}{index + 1}",
                "kind": "street",
                "zone": None,
            }
        )
    return streets


def _walk_seconds(a: dict[str, Any], b: dict[str, Any]) -> int:
    dx = a["map"]["x"] - b["map"]["x"]
    dy = a["map"]["y"] - b["map"]["y"]
    distance = (dx * dx + dy * dy) ** 0.5
    seconds = int(WALK_SECONDS_BASE + distance * WALK_SECONDS_PER_UNIT)
    return max(WALK_SECONDS_MIN, min(WALK_SECONDS_MAX, seconds))


def _jitter(rng: random.Random, center: tuple[float, float], radius: float = 70.0) -> dict[str, float]:
    return {
        "x": round(min(CANVAS_WIDTH - 40, max(40, center[0] + rng.uniform(-radius, radius))), 1),
        "y": round(min(CANVAS_HEIGHT - 40, max(40, center[1] + rng.uniform(-radius, radius))), 1),
    }


def _ensure_core_slots(
    template: dict[str, Any], venue_slots: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    """Append any missing everyday-life venue, deterministically, without touching RNG.

    ``venue_slots`` is the *existing* fixed + weighted draw and is returned unchanged when it
    already carries every core id.  Only when a core is missing is the template's own slot
    definition appended at the end, so the shuffled draw, coordinate jitter and walk-time
    sequence of an already-complete world stay byte-identical.  No new generator, no new
    topology rule: the appended slot goes through the same location/edge/rule assembly.
    """

    required_cores = tuple(template.get("core_location_ids", CORE_LOCATION_IDS))
    present = {str(slot.get("id") or slot.get("slot")) for slot in venue_slots}
    missing = [core for core in required_cores if core not in present]
    if not missing:
        return venue_slots
    catalogue: dict[str, dict[str, Any]] = {}
    for slot in (list(template["fixed_slots"]) + list(template["slot_pool"])
                 + list(template.get("core_slots", []))):
        catalogue.setdefault(str(slot.get("id") or slot.get("slot")), slot)
    filled = list(venue_slots)
    for core in missing:
        definition = catalogue.get(core)
        if definition is None:  # pragma: no cover - every shipped template declares its cores
            continue
        filled.append(dict(definition))
    return filled


def generate_topology(
    rng: random.Random,
    template: dict[str, Any],
    world_name: str,
    *,
    target_venue_count: Optional[int] = None,
    proposal: Optional[dict[str, Any]] = None,
) -> dict[str, Any]:
    """生成地点、区域、连接与步行耗时。"""
    procedural_mode = bool(template.get("procedural_mode"))
    if procedural_mode:
        layout_style = str(template.get("street_layout_style") or rng.choice(STREET_LAYOUT_STYLES))
        if layout_style not in _PROCEDURAL_STREET_LAYOUTS:
            layout_style = "star_hub"
        anchors, street_edge_pairs = _PROCEDURAL_STREET_LAYOUTS[layout_style]
        street_count = len(anchors)
    else:
        layout_style = "star_hub"
        anchors = _STREET_ANCHORS
        street_count = rng.randint(2, 3)
        street_edge_pairs = [(0, idx) for idx in range(1, street_count)]

    zone_defs = list(template["zones"])
    rng.shuffle(zone_defs)
    streets = _slugify_streets(rng, template, street_count)

    # 街道锚点：经典模式固定镇中心星形锚点；程序化模式按所选路网骨架展开并施加轻微坐标微扰。
    street_nodes: dict[str, dict[str, Any]] = {}
    for index, street in enumerate(streets):
        anchor = anchors[index]
        if procedural_mode:
            base_x = anchor[0] * CANVAS_WIDTH + rng.uniform(-18.0, 18.0)
            base_y = anchor[1] * CANVAS_HEIGHT + rng.uniform(-18.0, 18.0)
            map_xy = {
                "x": round(min(CANVAS_WIDTH - 50, max(50, base_x)), 1),
                "y": round(min(CANVAS_HEIGHT - 50, max(50, base_y)), 1),
            }
        else:
            map_xy = {
                "x": round(anchor[0] * CANVAS_WIDTH, 1),
                "y": round(anchor[1] * CANVAS_HEIGHT, 1),
            }
        node = {
            "location_id": street["location_id"],
            "name": street["name"],
            "kind": "street",
            "area_id": street["location_id"],
            "description": f"{street['name']}，镇上的主要街道之一。",
            "zone_id": "streets",
            "map": map_xy,
        }
        street_nodes[street["location_id"]] = node

    # 区 → 街道：按顺序轮转分配，让每个区都有归属街道。
    zone_street: dict[str, str] = {}
    for index, zone in enumerate(zone_defs):
        zone_street[zone["zone_id"]] = streets[index % street_count]["location_id"]

    # 选地点池：固定槽位 + 加权抽取（GLM 提案可加权部分槽位）。
    venue_slots = list(template["fixed_slots"])
    pool = list(template["slot_pool"])
    if proposal and proposal.get("building_emphasis"):
        for slot in pool:
            weight = proposal["building_emphasis"].get(slot.get("id"))
            if weight:
                slot["weight"] = max(1, int(slot.get("weight", 1)) * int(weight))
    budget = target_venue_count
    if budget is None:
        budget_range = template.get("venue_budget_range")
        if isinstance(budget_range, (list, tuple)) and len(budget_range) == 2:
            budget = rng.randint(int(budget_range[0]), int(budget_range[1]))
        else:
            budget = rng.randint(9, 16)
    budget = max(1, min(budget, len(pool)))
    picked = pick_weighted(rng, pool, budget)
    venue_slots.extend(picked)
    venue_slots = _ensure_core_slots(template, venue_slots)

    zone_centers: dict[str, tuple[float, float]] = {}
    zone_list = [zone["zone_id"] for zone in template["zones"]]
    zone_anchors = [(0.20, 0.20), (0.80, 0.20), (0.20, 0.80), (0.80, 0.80)]
    for index, zone_id in enumerate(zone_list):
        anchor = zone_anchors[index % len(zone_anchors)]
        zone_centers[zone_id] = (anchor[0] * CANVAS_WIDTH, anchor[1] * CANVAS_HEIGHT)

    prefix_pool = template["world_name_fragments"]["prefix"]
    locations: list[dict[str, Any]] = []
    edges: list[dict[str, Any]] = []
    rules: dict[str, Any] = {}

    for slot in venue_slots:
        location_id = slot["id"]
        zone_id = slot.get("zone") or "residential"
        home_street = zone_street.get(zone_id, streets[0]["location_id"])
        if location_id == "home":
            # 住宅挂在住宅区街道上；坐标围绕所属街道附近抖动。
            anchor = street_nodes[home_street]["map"]
            map_pos = _jitter(rng, (anchor["x"] + 90, anchor["y"] - 90), 40)
        elif location_id == "school":
            anchor = street_nodes[home_street]["map"]
            map_pos = _jitter(rng, (anchor["x"] - 120, anchor["y"] + 60), 50)
        else:
            center = zone_centers.get(zone_id, zone_centers[zone_list[0]])
            map_pos = _jitter(rng, center)
        name = compose_name(rng, slot.get("names") or [zone_id], world_name=world_name, prefix_pool=prefix_pool)
        description = compose_description(rng, slot.get("descriptions") or ["一座普通的镇上设施。"])
        location = {
            "location_id": location_id,
            "name": name,
            "kind": slot["kind"],
            "area_id": "bedroom" if location_id == "home" else location_id,
            "description": description,
            "reachable": [],
            "map": map_pos,
            "zone_id": zone_id,
        }
        if location_id == "home":
            if slot.get("rooms"):
                location["rooms"] = [dict(room) for room in slot["rooms"]]
            else:
                location["rooms"] = [
                    {
                        "room_id": "bedroom",
                        "name": "自己的房间",
                        "description": "自己的房间，有一张床和一张书桌。",
                    }
                ]
        locations.append(location)

        open_raw, close_raw = slot.get("open_hour"), slot.get("close_hour")
        open_hour = rng.randint(*open_raw) if isinstance(open_raw, list) else open_raw
        close_hour = rng.randint(*close_raw) if isinstance(close_raw, list) else close_raw
        affordances = _template_affordances(
            slot.get("affordances", []), where=f"slot {location_id}.affordances"
        )
        rules[location_id] = {
            "open_hour": open_hour,
            "close_hour": close_hour,
            "weekdays_only": bool(slot.get("weekdays_only", False)),
            "affordances": affordances,
        }
    # 连接：街道按拓扑骨架连通 + 各区地点挂街道 + 住宅挂街道。
    main_street = streets[0]["location_id"]
    for idx_a, idx_b in street_edge_pairs:
        street_a = streets[idx_a]["location_id"]
        street_b = streets[idx_b]["location_id"]
        edges.append(
            {
                "from": street_a,
                "to": street_b,
                "walk_seconds": _walk_seconds(street_nodes[street_a], street_nodes[street_b]),
            }
        )
    street_ids = [street["location_id"] for street in streets]
    for index, location in enumerate(locations):
        zone_id = location["zone_id"]
        if procedural_mode and location["location_id"] not in ("home", "school"):
            preferred = zone_street.get(zone_id, main_street)
            home_street_id = preferred if index % 2 == 0 else street_ids[(index + street_ids.index(preferred)) % len(street_ids)]
        else:
            home_street_id = zone_street.get(zone_id, main_street)
        if home_street_id not in street_ids:  # pragma: no cover - 模板错误防护
            home_street_id = main_street
        edges.append(
            {
                "from": location["location_id"],
                "to": home_street_id,
                "walk_seconds": _walk_seconds(location, street_nodes[home_street_id]),
            }
        )
    # 少量区内捷径，让路线选择更有意思。
    shortcut_budget = rng.randint(0, 2)
    for _ in range(shortcut_budget):
        zone_id = rng.choice(zone_list)
        zone_members = [loc for loc in locations if loc["zone_id"] == zone_id]
        if len(zone_members) < 2:
            continue
        first, second = rng.sample(zone_members, 2)
        pair = {first["location_id"], second["location_id"]}
        if any({edge["from"], edge["to"]} == pair for edge in edges):
            continue
        edges.append(
            {
                "from": first["location_id"],
                "to": second["location_id"],
                "walk_seconds": _walk_seconds(first, second),
            }
        )

    # reachable 由边对称推导。
    adjacency: dict[str, list[str]] = {loc["location_id"]: [] for loc in locations}
    adjacency.update({street_id: [] for street_id in street_ids})
    for edge in edges:
        adjacency[edge["from"]].append(edge["to"])
        adjacency[edge["to"]].append(edge["from"])
    all_locations = locations + [street_nodes[street_id] for street_id in street_ids]
    for location in all_locations:
        location["reachable"] = sorted(adjacency[location["location_id"]])
    # 街道也要有规则（street: 全天开放，可散步）。
    street_rule = {
        "open_hour": None,
        "close_hour": None,
        "weekdays_only": False,
        "affordances": _template_affordances(
            template["street_slot"]["affordances"], where="street_slot.affordances"
        ),
    }
    for street in streets:
        rules[street["location_id"]] = dict(street_rule)

    return {
        "locations": all_locations,
        "edges": edges,
        "location_rules": rules,
        "zone_names": {zone["zone_id"]: zone["name"] for zone in template["zones"]},
        "zone_street": zone_street,
        "street_layout_style": layout_style,
    }


def build_seed_material(seed: int, theme: str) -> str:
    return f"nyairo-worldgen|{GENERATOR_VERSION}|{theme}|{seed}"


def generate_world(
    *,
    seed: int,
    theme: Optional[str] = PROCEDURAL_THEME,
    world_name: Optional[str] = None,
    timezone_name: str = "Asia/Tokyo",
    target_venue_count: Optional[int] = None,
    proposal: Optional[dict[str, Any]] = None,
) -> dict[str, dict[str, Any]]:
    """生成一个完整世界包文档集合（未写盘）。

    ``proposal``（v0.4）是 GLM 世界设计提案（见 providers.glm.propose_world）：
    程序据此调整槽位权重、世界描述、环境事件候选与 NPC 作息——提案不承担
    拓扑权威，未知槽位建议被丢弃，几何与合法性仍完全由程序决定。
    """
    resolved_theme = normalize_theme(theme)
    template = (
        load_theme(resolved_theme, seed=seed)
        if resolved_theme == PROCEDURAL_THEME
        else load_theme(resolved_theme)
    )
    theme = resolved_theme
    rng = random.Random(build_seed_material(seed, theme))
    name = world_name or compose_world_name(rng, template["world_name_fragments"])
    # 防御性去重：world_id 只允许 ASCII slug。
    slug = re.sub(r"[^a-z0-9]+", "_", theme.lower()).strip("_")
    world_id = f"{slug}_{seed}"

    topology = generate_topology(
        rng, template, name,
        target_venue_count=target_venue_count, proposal=proposal,
    )
    location_ids = {loc["location_id"] for loc in topology["locations"]}
    street_ids = [loc["location_id"] for loc in topology["locations"] if loc["kind"] == "street"]

    # ---- NPC -------------------------------------------------------------
    npc_pool = [role for role in template["npc_role_pool"] if role["slot"] in location_ids]
    rng.shuffle(npc_pool)
    npc_count = min(len(npc_pool), rng.randint(3, 6))
    used_names: set[str] = set()
    npcs: list[dict[str, Any]] = []
    name_pool = template["npc_name_pool"]
    npc_index = 0
    for role in npc_pool:
        if len(npcs) >= npc_count:
            break
        for _attempt in range(24):
            family = rng.choice(name_pool["family"])
            given = rng.choice(name_pool["given_adult" if role["age"] == "adult" else "given_minor"])
            display_name = f"{family}{given}"
            if display_name not in used_names:
                used_names.add(display_name)
                break
        else:  # pragma: no cover - 名字池耗尽
            display_name = f"{name_pool['family'][0]}{npc_index}"
        npc_index += 1
        slot_location = role["slot"]
        # 工作窗口与营业时间对齐（一致性：店员不会在打烊时段上班）。
        rule = topology["location_rules"].get(slot_location, {})
        open_hour = rule.get("open_hour")
        close_hour = rule.get("close_hour")
        start_hour = role["start_hour"]
        end_hour = role["end_hour"]
        if open_hour is not None:
            start_hour = max(start_hour, open_hour)
            end_hour = min(end_hour, close_hour if close_hour is not None else end_hour)
        if end_hour <= start_hour:
            start_hour, end_hour = role["start_hour"], role["end_hour"]
        windows = [
            {
                "weekdays": list(role["weekdays"]),
                "start_minute": start_hour * 60,
                "end_minute": end_hour * 60,
                "location_id": slot_location,
            }
        ]
        # 下班后/休息日的公共生活窗口（成人：公园/街道/咖啡馆）。
        if role["age"] == "adult" and rng.random() < 0.7:
            public_spots = [
                loc["location_id"]
                for loc in topology["locations"]
                if loc["kind"] in ("park", "street", "cafe") and loc["location_id"] != slot_location
            ]
            if public_spots:
                if rng.random() < 0.5:
                    windows.append(
                        {
                            "weekdays": [6, 7],
                            "start_minute": rng.choice((10, 11, 14)) * 60,
                            "end_minute": rng.choice((16, 17)) * 60,
                            "location_id": rng.choice(public_spots),
                        }
                    )
                else:
                    windows.append(
                        {
                            "weekdays": [1, 2, 3, 4, 5],
                            "start_minute": min(22, end_hour + 1) * 60,
                            "end_minute": min(23, end_hour + 2) * 60,
                            "location_id": rng.choice(public_spots),
                        }
                    )
        npcs.append(
            {
                "npc_id": f"{theme.split('_')[0]}_npc_{slot_location}_{npc_index:02d}",
                "display_name": display_name,
                "age_classification": role["age"],
                "public_role": role["role"],
                "home_base_area": slot_location,
                "public_description": f"{name}的{role['role']}。",
                "windows": windows,
            }
        )

    # ---- 环境事件 ----------------------------------------------------------
    ambient_candidates = [
        item
        for item in template["ambient_pool"]
        if item["slot"] == "home" or item["slot"] in location_ids or item["slot"] == "street"
    ]
    rng.shuffle(ambient_candidates)
    ambient_templates = []
    for item in ambient_candidates[:6]:
        target_location = (
            rng.choice(street_ids)
            if item["slot"] == "street"
            else ("home" if item["slot"] == "home" else item["slot"])
        )
        ambient_templates.append(
            {
                "event_type": item["event_type"],
                "location_id": target_location,
                "summary": rng.choice(item["summaries"]),
                "start_hour": item["start_hour"],
                "end_hour": item["end_hour"],
            }
        )
    # GLM 提案的公共活动 → 确定性事件候选（挂同主题地点）。
    if proposal and proposal.get("public_activities"):
        import hashlib as _hashlib

        kind_by_slot = {}
        for loc in topology["locations"]:
            kind_by_slot.setdefault(loc["kind"], loc["location_id"])
        hint_map = {"便利店": "convenience_store", "学校": "school", "公园": "park",
                    "书店": "bookstore", "咖啡": "cafe", "集市": "market",
                    "车站": "station", "神社": "shrine"}
        for activity in proposal["public_activities"][:4]:
            slug = "local_" + _hashlib.sha1(activity.encode("utf-8")).hexdigest()[:8]
            target = kind_by_slot.get("park") or next(iter(kind_by_slot.values()))
            for hint, kind in hint_map.items():
                if hint in activity and kind_by_slot.get(kind):
                    target = kind_by_slot[kind]
                    break
            ambient_templates.append(
                {"event_type": slug, "location_id": target,
                 "summary": activity, "start_hour": 0, "end_hour": 24}
            )
    # 至少保证一条 home 事件，观察里始终有生活气息。
    if not any(item["location_id"] == "home" for item in ambient_templates):
        for item in template["ambient_pool"]:
            if item["slot"] == "home":
                ambient_templates.append(
                    {
                        "event_type": item["event_type"],
                        "location_id": "home",
                        "summary": rng.choice(item["summaries"]),
                        "start_hour": item["start_hour"],
                        "end_hour": item["end_hour"],
                    }
                )
                break

    # ---- 对象目录 ----------------------------------------------------------
    objects = []
    for item in template["object_pool"]:
        if item.get("location_only") and item["location"] not in location_ids:
            continue
        obj_index = len(objects)
        location_id = item["location"] if item["location"] in location_ids else "home"
        portable = bool(item.get("portable", False))
        capacity = int(item.get("capacity", 0) or 0)
        if "affordance_traits" in item:
            traits = schema.normalize_affordance_traits(
                list(item["affordance_traits"]),
                f"objects.objects[{obj_index}].affordance_traits",
            )
        else:
            traits = infer_affordance_traits(
                item["kind"],
                name=item["name"],
                portable=portable,
                note=item["note"],
            )
        raw_profile = (
            dict(item["matter_profile"])
            if "matter_profile" in item
            else infer_matter_profile(
                item["kind"],
                name=item["name"],
                portable=portable,
                capacity=capacity,
                note=item["note"],
                affordance_traits=traits,
            )
        )
        obj_entry: dict[str, Any] = {
            "object_id": item["object_id"],
            "name": item["name"],
            "kind": item["kind"],
            "location_id": location_id,
            "note": item["note"],
            "affordance_traits": traits,
            "matter_profile": schema.normalize_matter_profile(
                raw_profile,
                f"objects.objects[{obj_index}].matter_profile",
            ),
        }
        if "sale_spec" in item and item["sale_spec"] is not None:
            obj_entry["sale_spec"] = schema.normalize_sale_spec(
                item["sale_spec"],
                f"objects.objects[{obj_index}].sale_spec",
            )
        objects.append(obj_entry)

    # ---- 本地内容（无 LLM 时的完整可运行内容） -----------------------------
    flavor = template["flavor_pool"]
    world_tagline = rng.choice(flavor["world_intro"])
    if proposal and proposal.get("npc_rhythm"):
        world_tagline = f"{world_tagline}{proposal['npc_rhythm']}"
    entries: dict[str, Any] = {
        "world": {
            "tagline": world_tagline,
            "festivals": rng.sample(flavor["festival_candidates"], k=min(2, len(flavor["festival_candidates"]))),
        }
    }
    if template.get("procedural_mode"):
        entries["world"]["street_layout_style"] = topology["street_layout_style"]
        if template.get("biome_mix"):
            entries["world"]["biome_mix"] = list(template["biome_mix"])
        home_loc = next(
            (loc for loc in topology["locations"] if loc["location_id"] == "home"),
            None,
        )
        if home_loc and home_loc.get("rooms"):
            entries["world"]["home_layout"] = [
                room["room_id"] for room in home_loc["rooms"]
            ]
    if proposal and proposal.get("area_life"):
        for zone_name, life in proposal["area_life"].items():
            entries.setdefault("world", {}).setdefault("zone_life", []).append(f"{zone_name}：{life}")
    # v0.4 改进（批量实验 6.4）：intro 注入种子化风味句，避免同主题不同
    # 种子的介绍完全相同（本地模板模式的重复率问题在 40 世界实验中实测）。
    zone_flavor = flavor.get("zone_flavor", [])
    zone_items = (
        [item for items in zone_flavor.values() for item in items]
        if isinstance(zone_flavor, dict)
        else list(zone_flavor)
    )
    flavor_sentences = list(flavor["street_flavor"]) + zone_items
    # v0.4 第三轮改进（GLM 评审反馈）：风味句在世界内洗牌后逐地点分配，
    # 不重复使用，避免"杂货店冰柜"同时出现在书店与海滩。
    rng.shuffle(flavor_sentences)
    flavor_cursor = {"index": 0}

    def next_flavor() -> str:
        if not flavor_sentences:
            return ""
        sentence = flavor_sentences[flavor_cursor["index"] % len(flavor_sentences)]
        flavor_cursor["index"] += 1
        return sentence
    #: 固定槽位与可选池都可能带地点自己的那页文字（书店的 reading 就是一例）；
    #: 只读 slot_pool 会让挪进 fixed_slots 的地点丢掉它。
    reading_by_location = {
        str(slot.get("slot") or slot.get("id")): slot["reading"].strip()
        for slot in list(template["fixed_slots"]) + list(template["slot_pool"])
        if isinstance(slot.get("reading"), str) and slot["reading"].strip()
    }
    for location in topology["locations"]:
        intro = location["description"]
        if flavor_sentences and rng.random() < 0.65:
            flavor_bit = next_flavor()
            if flavor_bit and flavor_bit not in intro:
                intro = f"{intro}{flavor_bit}。"
        entry: dict[str, Any] = {"intro": intro}
        if location["kind"] == "street":
            entry["flavor"] = rng.choice(flavor["street_flavor"])
        # 地点自己带的文字（书里的一页、墙上的告示）。模板给了就抄进 content.json；
        # 没给就什么都不加，旧包的形状一分不变。
        if location["location_id"] in reading_by_location:
            entry["reading"] = reading_by_location[location["location_id"]][:400]
        entries[location["location_id"]] = entry
    for npc in npcs:
        entries[npc["npc_id"]] = {"public_note": f"{npc['display_name']}是这里的{npc['public_role']}。"}

    # 为商业地点写入随世界主题/种子生成的日常商品表；独立随机流，不扰动已有地形与对象。
    shop_rng = random.Random(f"{build_seed_material(seed, theme)}:shop_goods")
    storefront = _open_storefront()
    for location in topology["locations"]:
        if location["kind"] not in storefront.COMMERCIAL_LOCATION_KINDS:
            continue
        loc_id = location["location_id"]
        loc_objects = [o for o in objects if o.get("location_id") == loc_id]
        goods = storefront.generate_package_goods_for_location(
            loc_id=loc_id,
            loc_name=location["name"],
            loc_kind=location["kind"],
            intro=str(entries[loc_id].get("intro") or ""),
            object_rows=loc_objects,
            theme=theme,
            rng=shop_rng,
        )
        if goods:
            entries[loc_id]["goods"] = goods

    if template.get("procedural_mode"):
        description = f"{name}——融合{template['theme_name']}风貌的程序化生成小镇。"
    else:
        description = f"{name}——{template['theme_name']}主题的生成世界。"
    if proposal and proposal.get("style"):
        description = f"{name}——{proposal['style']}"
        if proposal.get("culture"):
            description += proposal["culture"]
    world_doc = {
        "schema_version": schema.WORLD_SCHEMA,
        "world_id": world_id,
        "name": name,
        "theme": theme,
        "seed": seed,
        "timezone": timezone_name,
        "generator_version": GENERATOR_VERSION,
        "description": description,
    }
    topology_doc = {
        "schema_version": schema.TOPOLOGY_SCHEMA,
        "locations": topology["locations"],
        "edges": topology["edges"],
    }
    rules_doc = {
        "schema_version": schema.RULES_SCHEMA,
        "location_rules": topology["location_rules"],
        "weather_candidates": list(template["weather"]),
    }
    npcs_doc = {"schema_version": schema.NPCS_SCHEMA, "npcs": npcs}
    ambient_doc = {"schema_version": schema.AMBIENT_SCHEMA, "templates": ambient_templates}
    objects_doc = {"schema_version": schema.OBJECTS_SCHEMA, "objects": objects}
    content_doc = {
        "schema_version": schema.CONTENT_SCHEMA,
        "source": "local",
        "model": None,
        "entries": entries,
    }

    docs = {
        "world.json": world_doc,
        "topology.json": topology_doc,
        "rules.json": rules_doc,
        "npcs.json": npcs_doc,
        "ambient.json": ambient_doc,
        "objects.json": objects_doc,
        "content.json": content_doc,
    }
    # 生成即自检：格式问题在写盘前就暴露。
    for name_key, validator in schema.DOC_VALIDATORS.items():
        docs[name_key] = validator(docs[name_key])
    return docs


_base_normalize_theme = normalize_theme


def normalize_theme(theme_id: Optional[str]) -> str:
    """规范化主题名；保持经典四主题 AVAILABLE_THEMES 不变的同时支持 ALL_TEMPLATE_THEMES（含 urban_apartment）。"""
    if isinstance(theme_id, str):
        cleaned = theme_id.strip().lower()
        if cleaned in ALL_TEMPLATE_THEMES:
            return cleaned
    return _base_normalize_theme(theme_id)


class TownPlace:
    """三句话开荒生成的单个镇域地点（含圈层 1/2/3 与渐进解锁状态）。"""

    def __init__(
        self,
        place_id: str,
        name_cn: str,
        ring_tier: int,
        unlocked: bool,
        edge_hint_cn: str = "",
    ) -> None:
        self.place_id = place_id
        self.name_cn = name_cn
        self.ring_tier = int(ring_tier)
        self.unlocked = bool(unlocked)
        self.edge_hint_cn = edge_hint_cn


class GeneratedWorldState:
    """三句话开荒世界状态：首轮立开第一圈，二/三圈随踩出脚步或天数自然渐进解锁。"""

    def __init__(
        self,
        *,
        terrain_base: str,
        climate_bias: str,
        outdoor_drying_zone: str,
        starter_objects: list[str],
        places: dict[str, TownPlace],
    ) -> None:
        self.terrain_base = terrain_base
        self.climate_bias = climate_bias
        self.outdoor_drying_zone = outdoor_drying_zone
        self.starter_objects = starter_objects
        self.places = places

    def visible_unlocked_places(self) -> list[str]:
        return [pid for pid, place in self.places.items() if place.unlocked]

    def step_toward_edge(self, target_place_id: str) -> TownPlace:
        place = self.places[target_place_id]
        place.unlocked = True
        place.edge_hint_cn = ""
        return place

    def advance_days_lived(self, days_lived: int) -> None:
        for place in self.places.values():
            if place.ring_tier == 2 and days_lived >= 2:
                place.unlocked = True
                place.edge_hint_cn = ""
            elif place.ring_tier == 3 and days_lived >= 7:
                place.unlocked = True
                place.edge_hint_cn = ""


def parse_opening_sentence(sentence_cn: str) -> tuple[str, str]:
    """第 57 / 69 / 89 章：从一句话描述里零 LLM 解析落脚地貌与气候底色。"""
    s = sentence_cn or ""
    if any(k in s for k in ("公寓", "高楼", "电梯", "高架")):
        terrain = "urban_apartment"
    elif any(k in s for k in ("海", "港", "礁石", "潮")):
        terrain = "coastal_town"
    elif any(k in s for k in ("山", "雾", "温泉", "汤", "石阶")):
        terrain = "mountain_town"
    elif any(k in s for k in ("稻", "田", "村", "水渠")):
        terrain = "rural_farming"
    else:
        terrain = "residential_town"

    if any(k in s for k in ("雨", "潮", "梅雨")):
        climate = "humid_breezy"
    elif any(k in s for k in ("雾", "凉", "雪")):
        climate = "misty_cool"
    else:
        climate = "mild_clear"
    return terrain, climate


def hatch_world_from_three_inputs(
    *,
    opening_sentence_cn: str,
    starter_objects: list[str] | tuple[str, ...],
    is_legacy_upgrade: bool = False,
) -> GeneratedWorldState:
    """三步 1 秒生成落脚世界；都市公寓自动启用封窗阳台，老存档全三圈初始解锁。"""
    terrain, climate = parse_opening_sentence(opening_sentence_cn)
    drying_zone = "balcony" if terrain == "urban_apartment" else "courtyard"
    chosen_objs = list(starter_objects[:2]) if starter_objects else ["暖黄旧台灯", "空白速写本"]
    ring23_open = bool(is_legacy_upgrade)

    places = {
        "home": TownPlace("home", "自己的小家", 1, True),
        drying_zone: TownPlace(drying_zone, "封窗小阳台" if drying_zone == "balcony" else "门外小院", 1, True),
        "convenience_store": TownPlace("convenience_store", "街角便利店", 1, True),
        "old_bookstore": TownPlace("old_bookstore", "温井旧书店", 1, True),
        "promenade": TownPlace(
            "promenade",
            "海堤散步道" if terrain == "coastal_town" else "河堤散步道",
            2,
            ring23_open,
            "" if ring23_open else "往西延伸的石板路（还没去逛过）",
        ),
        "flower_craft_shop": TownPlace(
            "flower_craft_shop",
            "巷口花店与手作铺",
            2,
            ring23_open,
            "" if ring23_open else "拐角飘来花草味的小巷（还没去逛过）",
        ),
        "far_lookout": TownPlace(
            "far_lookout",
            "退潮灯塔礁石滩" if terrain == "coastal_town" else "山坡展望台",
            3,
            ring23_open,
            "" if ring23_open else "更远处的坡道尽头（留待周末去走走）",
        ),
    }

    return GeneratedWorldState(
        terrain_base=terrain,
        climate_bias=climate,
        outdoor_drying_zone=drying_zone,
        starter_objects=chosen_objs,
        places=places,
    )


